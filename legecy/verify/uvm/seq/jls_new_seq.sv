   `uvm_object_utils(jls_chipaddr_255_10_seq)
	logic [31:0] chip_id;
	logic [31:0] reg_targeth;

   //////////////////////////////////////////////////////////////
   // Function Used To "New" The Class
   //////////////////////////////////////////////////////////////
   function new(string name="jls_chipaddr_255_10_seq");
      super.new(name);
   endfunction : new

   task pre_body();
     super.pre_body();

   endtask

   task body();
		super.body();

     	`uvm_info(get_type_name(), "jls_chipaddr_255_10_seq start", UVM_MEDIUM);
    	//loop 230_239
    	for(int i = `JLS_NUM_START; i < `JLS_NUM_END; i++) begin
    		#100;
    		//read chip id for each addr
			top_vif.chipaddr = i;
			ral.comm.reg_chip_id.rd(chip_id);
			if(chip_id != i) begin
				`uvm_error(get_type_name(), $sformatf("Chip_id is not right, should be %d, but actual is %d", i, chip_id[9:0]))
			end

			//write data, then read and check value
			ral.work.reg_targeth.wr(32'hffffffff);
			//ral.work.reg_targeth.rd(reg_targeth);
