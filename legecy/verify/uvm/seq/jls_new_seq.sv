class jls_ecc1_jlm_seq extends jls_base_seq;
   `uvm_object_utils(jls_ecc1_jlm_seq)
	logic [31:0] chip_id;
	logic [31:0] reg_targeth;
	logic [31:0] ecc1;
	logic [31:0] ecc2;

   //////////////////////////////////////////////////////////////
   // Function Used To "New" The Class
   //////////////////////////////////////////////////////////////
   function new(string name="jls_ecc1_jlm_seq");
      super.new(name);
   endfunction : new

   task pre_body();
     super.pre_body();

   endtask

   task body();
		super.body();

     	`uvm_info(get_type_name(), "jls_ecc1_jlm_seq start", UVM_MEDIUM);
			initm_wb_eccs_jlm();
			for(int i = 0; i < 1; i++) begin
				#100;
				top_vif.chipaddr = i;
				ral.comm.reg_chip_id.rd(chip_id);
				if(chip_id != i) begin
					`uvm_error(get_type_name(), $sformatf("chip_id should be %d, but actual is %d", i, chip_id))
				end
				waitm_wb_do_empty_jlm();
				uvm_hdl_deposit("tb_top.g_jlm_ecc_enc",43'h10_0000);//write inject 4 ecc1 (cmd,addr,nop,write)
				ral.work.reg_targeth.wr(32'h20191202);
				waitm_wb_do_empty_jlm();
				uvm_hdl_deposit("tb_top.g_jlm_ecc_enc", 0);
				ral.work.reg_targeth.mir(UVM_CHECK);
				waitm_wb_do_empty_jlm();
				ral.comm.reg_ecc1.rd(ecc1);
				if(ecc1 != 32'h4) begin
					`uvm_error(get_type_name(), $sformatf("ecc1 should be %d, but actual is %d", 32'h4, ecc1))
				end
				waitm_wb_do_empty_jlm();
				uvm_hdl_deposit("tb_top.g_jlm_ecc_enc",43'h20000_0000);
				ral.work.reg_targeth.wr(32'h20200430);
				waitm_wb_do_empty_jlm();
    			uvm_hdl_deposit("tb_top.g_jlm_ecc_enc", 0);
				ral.work.reg_targeth.mir(UVM_CHECK);
				waitm_wb_do_empty_jlm();
				ral.comm.reg_ecc1.rd(ecc1);
				if(ecc1 != 32'h8) begin
					`uvm_error(get_type_name(), $sformatf("ecc1 should be %d, but actual is %d", 32'h8, ecc1))
				end

			end
			#50000;

     	`uvm_info(get_type_name(), "jls_ecc1_jlm_seq end", UVM_MEDIUM);

   endtask

endclass