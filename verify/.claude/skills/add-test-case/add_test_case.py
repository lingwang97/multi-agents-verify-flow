#!/usr/bin/env python3
"""Scaffold a new UVM leaf test case (test class + seq class + JSON entry)
for the verify environment, following its inheritance and naming
conventions. See SKILL.md in this directory for the full walkthrough.

Usage:
  python add_test_case.py --module <mod> --function write_read --level system
  python add_test_case.py --module <mod> --function burn_and_read --level block \
      --stage1 true --smoke true --iteration 1

The valid modules are the keys of json/module.json (regenerated by every
`gen_uvm_env.py --guvc`), so nothing here changes when modules are added or
removed.

Creates:
  - class <module>_<function>_test in test/<module>_test.sv (system)
                                 or test/<module>_block_base_test.sv (block)
  - class <module>_<function>_seq  in seq/<module>_seq.sv (system)
                                 or seq/<module>_block_base_seq.sv (block)
  - a new entry keyed "<module>_<function>_test" in json/case/<module>.json
"""
import argparse
import json
import os
import re
import sys

# This script lives at verify/.claude/skills/add-test-case/ -
# walk up 3 levels to reach verify (the "verify root").
VERIFY_ROOT = os.path.normpath(
    os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "..")
)


def load_modules():
    """Module names from json/module.json - the generated index of the case files."""
    path = os.path.join(VERIFY_ROOT, "json", "module.json")
    try:
        with open(path, "r", encoding="utf-8") as f:
            mods = json.load(f).get("modules", {})
    except (OSError, ValueError):
        return []
    return list(mods)


def die(msg):
    print("ERROR: " + msg, file=sys.stderr)
    sys.exit(1)


def valid_ident(name):
    return re.match(r"^[A-Za-z_][A-Za-z0-9_]*$", name) is not None


def class_exists(path, class_name):
    with open(path, "r", encoding="utf-8") as f:
        content = f.read()
    return re.search(r"\bclass\s+" + re.escape(class_name) + r"\b", content) is not None


_PP_OPEN = re.compile(r"\s*`(ifdef|ifndef)\b")
_PP_CLOSE = re.compile(r"\s*`endif\b")
_CLASS_OPEN = re.compile(r"\s*(virtual\s+)?class\b")
_CLASS_CLOSE = re.compile(r"\s*endclass\b")


def _code_lines(lines):
    """(index, stripped text) of the lines that are not blank and not // comments."""
    return [(i, l.strip()) for i, l in enumerate(lines) if l.strip() and not l.strip().startswith("//")]


def _include_guard_end(lines):
    """Index of the closing `endif of a file-level include guard, else None.

    A guard is: first code line `ifndef X, the next one `define X, and the last
    code line `endif. Per-module test/seq files have no guard - their `endif
    lines belong to `ifdef OPEN_EDA blocks inside the classes and must never be
    taken as an insertion point."""
    code = _code_lines(lines)
    if len(code) < 3:
        return None
    m = re.match(r"`ifndef\s+(\w+)", code[0][1])
    if not m or not re.match(r"`define\s+%s\b" % re.escape(m.group(1)), code[1][1]):
        return None
    return code[-1][0] if code[-1][1].startswith("`endif") else None


def _top_level_at(lines, idx, expected_pp_depth):
    """True when line idx sits outside every class and at the expected preprocessor depth."""
    pp = cls = 0
    for l in lines[:idx]:
        if _PP_OPEN.match(l):
            pp += 1
        elif _PP_CLOSE.match(l):
            pp -= 1
        elif _CLASS_OPEN.match(l):
            cls += 1
        elif _CLASS_CLOSE.match(l):
            cls -= 1
    return pp == expected_pp_depth and cls == 0


def plan_class_insert(path, new_text):
    """New content of a per-module test/seq file with a top-level class added.

    Inside a file-level include guard: before its closing `endif. Otherwise:
    appended at the end of the file. Refuses (dies, nothing written) when the
    insertion point would land inside a class or inside an `ifdef block - a
    class placed there compiles but never registers with the factory (UVM
    BDTYP/INVTST at run time). Callers plan every file before writing any, so
    a refusal leaves no partial edit."""
    with open(path, "r", encoding="utf-8", newline="") as f:   # keep the file's own line endings
        lines = f.readlines()
    end = _include_guard_end(lines)
    if end is not None:
        idx, depth = end, 1
    else:
        idx, depth = len(lines), 0
        if lines and not lines[-1].endswith("\n"):
            lines[-1] += "\n"
    if not _top_level_at(lines, idx, depth):
        die("Cannot place a new class at top level of %s: the insertion point would be inside a class "
            "or an `ifdef block (unbalanced class/`ifdef structure?). Nothing was written." % path)
    return "".join(lines[:idx] + [new_text] + lines[idx:])


def main():
    modules = load_modules()
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--module", required=True,
                    help="a module of json/module.json: " + (", ".join(modules) or "(none - run gen_uvm_env.py --guvc)"))
    ap.add_argument("--function", required=True, help="short scenario name, e.g. write_read (identifier chars only)")
    ap.add_argument("--level", required=True, choices=["system", "block"])
    ap.add_argument("--stage1", default=None, choices=["true", "false"])
    ap.add_argument("--stage2", default=None, choices=["true", "false"])
    ap.add_argument("--smoke", default="false", choices=["true", "false"])
    ap.add_argument("--full", default="true", choices=["true", "false"])
    ap.add_argument("--iteration", default="1")
    ap.add_argument("--codecoverage", default="true", choices=["true", "false"])
    ap.add_argument("--macro-opt", default="", dest="macro_opt",
                     help="extra +define+ tokens, appended after the block-test macro (if --level block)")
    ap.add_argument("--plusargs-opt", default="", dest="plusargs_opt")
    args = ap.parse_args()

    mod = args.module.strip().lower()
    func = args.function.strip()

    # stage1/stage2 are exclusive in every existing case entry (smoke tests are
    # stage1-only, regression tests are stage2-only) - default the one the
    # caller didn't set from the one they did, instead of letting both default
    # to "true" at once.
    if args.stage1 is None and args.stage2 is None:
        args.stage1, args.stage2 = "false", "true"
    elif args.stage1 is None:
        args.stage1 = "false" if args.stage2 == "true" else "true"
    elif args.stage2 is None:
        args.stage2 = "false" if args.stage1 == "true" else "true"

    if not modules:
        die("json/module.json lists no modules - generate the environment first (gen_uvm_env.py --guvc)")
    if mod not in modules:
        die("--module must be a module of json/module.json: %s (got %r)" % (", ".join(modules), mod))
    if not valid_ident(func):
        die("--function must be an identifier fragment (letters/digits/underscore, "
            "not starting with a digit): %r" % func)

    test_class = "%s_%s_test" % (mod, func)
    seq_class = "%s_%s_seq" % (mod, func)

    if args.level == "system":
        test_file = os.path.join(VERIFY_ROOT, "test", "%s_test.sv" % mod)
        seq_file = os.path.join(VERIFY_ROOT, "seq", "%s_seq.sv" % mod)
        test_base = "%s_base_test" % mod
        seq_base = "%s_base_seq" % mod
        start_target = "vseqr_h.%s_seqr_h" % mod
    else:
        test_file = os.path.join(VERIFY_ROOT, "test", "%s_block_base_test.sv" % mod)
        seq_file = os.path.join(VERIFY_ROOT, "seq", "%s_block_base_seq.sv" % mod)
        test_base = "%s_block_base_test" % mod
        seq_base = "%s_block_base_seq" % mod
        start_target = "%s_env_h.vseqr_h" % mod

    if not os.path.isfile(test_file) or not os.path.isfile(seq_file):
        if args.level == "block":
            die(
                "Module '%s' has no block-level base yet (missing %s and/or %s).\n"
                "Block level needs the %s / %s pair plus tb_top/filelist/uvm_blk_%s.f "
                "(generated by --guvc for a module with has_tb_top: true; the flow scripts pick the "
                "filelist up from +define+%s_BLOCK_TEST). Which modules have it: "
                "docs/memory/arch_memory.md section 0."
                % (mod, test_file, seq_file, test_base, seq_base, mod, mod.upper())
            )
        die("Module '%s' has no %s / %s yet - run gen_uvm_env.py --guvc first." % (mod, test_file, seq_file))

    json_file = os.path.join(VERIFY_ROOT, "json", "case", "%s.json" % mod)
    if not os.path.isfile(json_file):
        die("No case file found at %s" % json_file)

    if class_exists(test_file, test_class):
        die("Class %s already exists in %s" % (test_class, test_file))
    if class_exists(seq_file, seq_class):
        die("Class %s already exists in %s" % (seq_class, seq_file))

    with open(json_file, "r", encoding="utf-8") as f:
        case_data = json.load(f)
    if test_class in case_data.get("tests", {}):
        die("Test key %s already exists in %s" % (test_class, json_file))

    # ---- test class ----
    test_text = '''
class %(test_class)s extends %(test_base)s;

  `uvm_component_utils(%(test_class)s)

  function new(string name = "%(test_class)s", uvm_component parent);
    super.new(name, parent);
  endfunction

  task main_phase(uvm_phase phase);
    %(seq_class)s seq;
    super.main_phase(phase);
    phase.raise_objection(this);
    seq = %(seq_class)s::type_id::create("seq");
    seq.start(%(start_target)s);
    phase.drop_objection(this);
  endtask

endclass : %(test_class)s
''' % dict(test_class=test_class, test_base=test_base, seq_class=seq_class,
           start_target=start_target)

    new_test = plan_class_insert(test_file, test_text)

    # ---- seq class ----
    seq_text = '''
class %(seq_class)s extends %(seq_base)s;

  `uvm_object_utils(%(seq_class)s)

  function new(string name="%(seq_class)s");
    super.new(name);
  endfunction

  task body();
    super.body();
    // TODO: real stimulus for "%(func)s" goes here
  endtask

endclass : %(seq_class)s
''' % dict(seq_class=seq_class, seq_base=seq_base, func=func)

    new_seq = plan_class_insert(seq_file, seq_text)

    # both files planned without a refusal - only now write them
    for path, content in ((test_file, new_test), (seq_file, new_seq)):
        with open(path, "w", encoding="utf-8", newline="") as f:
            f.write(content)

    # ---- JSON entry ----
    macro_opt = args.macro_opt
    if args.level == "block":
        macro_opt = ("+%s_BLOCK_TEST" % mod.upper()) + macro_opt

    case_data.setdefault("tests", {})[test_class] = {
        "stage1": args.stage1,
        "stage2": args.stage2,
        "smoke": args.smoke,
        "full": args.full,
        "codecoverage": args.codecoverage,
        "iteration": args.iteration,
        "UVM_TESTNAME": test_class,
        "VCS_MACRO_OPT": macro_opt,
        "VCS_PLUSARGS_OPT": args.plusargs_opt,
    }
    with open(json_file, "w", encoding="utf-8") as f:
        json.dump(case_data, f, indent=4)
        f.write("\n")

    print("Added %s (test) to %s" % (test_class, test_file))
    print("Added %s (seq) to %s" % (seq_class, seq_file))
    print("Added JSON case '%s' to %s" % (test_class, json_file))
    print("")
    print("Next steps (see .claude/skills/add-test-case/test_case_dev_manual.md):")
    print("  1. Fill in %s::body() with real stimulus." % seq_class)
    print("  2. Wire real protocol signals/checks if this test needs them "
          "(interface/driver/monitor/scoreboard).")
    print("  3. Review VCS_MACRO_OPT/VCS_PLUSARGS_OPT in the new JSON entry.")
    print("  4. Run (from sim/): ./wsim_oeda -c %s -seed 1   (local oEDA), then ./wsim -c %s on VCS"
          % (test_class, test_class))


if __name__ == "__main__":
    main()
